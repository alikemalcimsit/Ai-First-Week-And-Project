import apiRequest from "../helpers/apiRequest";

const LM_STUDIO_URL = process.env.LM_STUDIO_URL || "http://192.168.1.208:1234/v1/chat/completions";

// ─────────────────────────────────────────────
// 1. DATA FETCHING
// ─────────────────────────────────────────────
async function fetchAllMessages(chatId) {
  try {
    const res = await apiRequest.post("/chatlist/last-100", { chatId });
    const messages = res?.data?.data || res?.data || res || [];
    return Array.isArray(messages) ? messages : [];
  } catch (error) {
    console.error(`ChatId ${chatId} için mesajlar çekilemedi:`, error.message);
    return [];
  }
}

// ─────────────────────────────────────────────
// 2. SAFE DECODE
// ─────────────────────────────────────────────
function safeDecode(text) {
  if (!text) return "";
  try {
    // '+' işaretlerini boşluğa çevir (Bazen URL encode işlemlerinde boşluklar + kalabiliyor)
    return decodeURIComponent(text.replace(/\+/g, '%20'));
  } catch {
    return text;
  }
}

// ─────────────────────────────────────────────
// 3. ROLE DETECTION
// ─────────────────────────────────────────────
function getRole(m) {
  // Gelen inbound ise user, kalan her durum (delivered, echo vs) assistant
  return m.status === "inbound" ? "user" : "assistant";
}

// ─────────────────────────────────────────────
// 4. CLEAN + NORMALIZE CHAT
// ─────────────────────────────────────────────
function prepareMessages(messages) {
  // 1. Çift mesajları temizle (Map kullanarak daha performanslı O(N) filtreleme)
  const uniqueMessagesMap = new Map();
  messages.forEach(m => {
    if (!uniqueMessagesMap.has(m.messageId)) {
      uniqueMessagesMap.set(m.messageId, m);
    }
  });

  return Array.from(uniqueMessagesMap.values())
    .filter(m => m.type === "text" && m.text?.trim()) // Sadece dolu text mesajlar
    .sort((a, b) => new Date(a.dateTime) - new Date(b.dateTime)) // Tarihe göre sırala
    .map(m => ({
      role: getRole(m),
      content: safeDecode(m.text)
    }));
}

